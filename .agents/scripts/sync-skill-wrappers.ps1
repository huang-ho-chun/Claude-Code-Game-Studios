[CmdletBinding()]
param(
    [switch]$Check
)

$ErrorActionPreference = 'Stop'

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$canonicalRoot = Join-Path $repoRoot '.claude\skills'
$wrapperRoot = Join-Path $repoRoot '.agents\skills'
$utf8NoBom = [System.Text.UTF8Encoding]::new($false)
$expectedFolders = [System.Collections.Generic.HashSet[string]]::new(
    [System.StringComparer]::OrdinalIgnoreCase
)
$drift = [System.Collections.Generic.List[string]]::new()

function Get-FrontmatterLine {
    param(
        [Parameter(Mandatory)] [string]$Frontmatter,
        [Parameter(Mandatory)] [string]$Key,
        [Parameter(Mandatory)] [string]$SourcePath
    )

    $matches = [regex]::Matches(
        $Frontmatter,
        "(?m)^$([regex]::Escape($Key)):\s*.*$"
    )
    if ($matches.Count -ne 1) {
        throw "$SourcePath must contain exactly one single-line '${Key}:' entry."
    }
    return $matches[0].Value.TrimEnd()
}

function Get-WrapperContent {
    param(
        [Parameter(Mandatory)] [string]$Folder,
        [Parameter(Mandatory)] [string]$CanonicalPath
    )

    $source = [IO.File]::ReadAllText($CanonicalPath)
    $frontmatterMatch = [regex]::Match($source, '(?s)^---\s*\r?\n(.*?)\r?\n---')
    if (-not $frontmatterMatch.Success) {
        throw "$CanonicalPath has no YAML frontmatter."
    }

    $nameLine = Get-FrontmatterLine $frontmatterMatch.Groups[1].Value 'name' $CanonicalPath
    $descriptionLine = Get-FrontmatterLine $frontmatterMatch.Groups[1].Value 'description' $CanonicalPath

    $content = @"
---
$nameLine
$descriptionLine
---

# Codex compatibility wrapper

<!-- Generated by .agents/scripts/sync-skill-wrappers.ps1. -->

Read ``.claude/skills/$Folder/SKILL.md`` completely and follow it as the canonical
workflow. Resolve its relative references from that canonical skill directory.
Apply the Claude-to-Codex vocabulary mapping in the repository ``AGENTS.md``.
Do not duplicate or reinterpret the workflow in this wrapper.
"@
    return ($content + "`n").Replace("`r`n", "`n")
}

if (-not (Test-Path -LiteralPath $canonicalRoot -PathType Container)) {
    throw "Canonical skill directory not found: $canonicalRoot"
}

if (-not $Check) {
    New-Item -ItemType Directory -Path $wrapperRoot -Force | Out-Null
}

$canonicalSkills = Get-ChildItem -LiteralPath $canonicalRoot -Directory | Sort-Object Name
foreach ($skillDirectory in $canonicalSkills) {
    $canonicalPath = Join-Path $skillDirectory.FullName 'SKILL.md'
    if (-not (Test-Path -LiteralPath $canonicalPath -PathType Leaf)) {
        continue
    }

    [void]$expectedFolders.Add($skillDirectory.Name)
    $expected = Get-WrapperContent $skillDirectory.Name $canonicalPath
    $wrapperDirectory = Join-Path $wrapperRoot $skillDirectory.Name
    $wrapperPath = Join-Path $wrapperDirectory 'SKILL.md'
    $actual = if (Test-Path -LiteralPath $wrapperPath -PathType Leaf) {
        [IO.File]::ReadAllText($wrapperPath).Replace("`r`n", "`n")
    } else {
        $null
    }

    if ($actual -ceq $expected) {
        continue
    }

    $drift.Add($skillDirectory.Name)
    if (-not $Check) {
        New-Item -ItemType Directory -Path $wrapperDirectory -Force | Out-Null
        [IO.File]::WriteAllText($wrapperPath, $expected, $utf8NoBom)
    }
}

$stale = @()
if (Test-Path -LiteralPath $wrapperRoot -PathType Container) {
    $stale = Get-ChildItem -LiteralPath $wrapperRoot -Directory |
        Where-Object { -not $expectedFolders.Contains($_.Name) } |
        Select-Object -ExpandProperty Name
}

if ($drift.Count -gt 0) {
    $verb = if ($Check) { 'Drifted' } else { 'Updated' }
    Write-Output ("${verb} wrappers: " + ($drift -join ', '))
}
if ($stale.Count -gt 0) {
    Write-Output ('Stale wrappers require manual review: ' + ($stale -join ', '))
}

if ($Check -and ($drift.Count -gt 0 -or $stale.Count -gt 0)) {
    exit 1
}
if ($stale.Count -gt 0) {
    exit 1
}

Write-Output ("Skill wrappers synchronized: $($expectedFolders.Count)")
